#program to find out area and perimeter of the circle
#creating variable to store radius of the circle
radius=5
#displaying radius of the circle
print("----- Circle -----")
print("Radius : ",radius,"cm")
#Displaying perimeter of the circle
print("Perimeter : ",(3.14*radius*2),"cm")
#Displaying area of the circle
print("Area : ",(3.14*radius**2),"sq cm")
